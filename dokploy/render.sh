#!/bin/sh
# Re-render dokploy/compose.yaml after `git merge upstream/main` or after editing dokploy/override.yaml.
# pre-rendered single file, because the Compose on the VPS ignores `!reset` inside YAML anchors.
set -e
cd "$(dirname "$0")/.."
{
  echo '# GENERATED by dokploy/render.sh from the upstream compose files + dokploy/override.yaml. Do not edit by hand.'
  docker compose -f compose.yaml -f compose.full.yaml -f compose.observability.yaml -f dokploy/override.yaml \
    --env-file .env --env-file .env.override --env-file dokploy/.env.example \
    config --no-interpolate --no-path-resolution
} > dokploy/compose.yaml.tmp
mv dokploy/compose.yaml.tmp dokploy/compose.yaml
